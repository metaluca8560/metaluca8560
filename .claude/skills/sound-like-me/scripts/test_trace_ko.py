def classify(sc):
    return '원문' if sc >= VERBATIM else ('손질' if sc >= EDITED else '작성')


def main():
    src = norm(TRANSCRIPT)
    ok, mine_ok = 0, 0
    print(f"기준: 원문 >= {VERBATIM}, 손질 >= {EDITED}\n")
    for want, s in CASES:
        sc = score(s, src)
        got = classify(sc)
        ok += got == want
        # 실제로 중요한 건 '내 말(원문+손질)'과 '작성'을 가르는 것
        mine_ok += (got == '작성') == (want == '작성')
        mark = '  ' if got == want else ('△ ' if (got == '작성') == (want == '작성') else '✗ ')
        print(f"{mark}{want}→{got} [{sc:.2f}] {s}")
    n = len(CASES)
    print(f"\n세 가지 분류 정확도: {ok}/{n}")
    print(f"내 말 / 새로 쓴 문장 구분 정확도: {mine_ok}/{n}")
    sys.exit(0 if mine_ok == n else 1)


if __name__ == '__main__':
    main()
